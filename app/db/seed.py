def _build_lesson_content(title: str, grade: int, kind: Literal["theory", "practice"]) -> dict:
    profile = _topic_profile(title, grade)
    is_theory = kind == "theory"

    overview = (
        f"Тема {grade} класса «{title}». На уроке разбираем ключевую идею, "
        f"пошаговый алгоритм и типовые задачи уровня школьной программы."
    )
    objectives = [
        f"Понять смысл темы «{title}» и где она используется.",
        "Освоить алгоритм решения без пропуска шагов.",
        "Научиться проверять ответ и находить типичные ошибки.",
    ]
    theory = (
        f"{profile.focus} {profile.formula} "
        "Важно не только получить ответ, но и обосновать каждый переход в решении."
    )
    if not is_theory:
        theory = (
            f"Практический блок по теме «{title}»: закрепляем правило на задачах разного уровня "
            "и отрабатываем аккуратную запись решений."
        )

    tasks = {
        "basic": [
            f"Выпишите главное правило темы «{title}» и объясните его своими словами.",
            "Решите 2 базовые задачи по алгоритму урока.",
        ],
        "medium": [
            "Решите задачу со смешанными вычислениями и обоснуйте каждый шаг.",
            "Составьте собственный пример и решите его полностью.",
        ],
        "advanced": [
            "Решите задачу повышенного уровня с проверкой двумя способами.",
            "Найдите и исправьте ошибку в чужом решении, объясните исправление.",
        ],
    }

    if not is_theory:
        tasks["basic"].append("Сделайте самопроверку по чек-листу: условие, формула, вычисления, ответ.")
        tasks["medium"].append("Сравните два способа решения и выберите более рациональный.")

    return {
        "overview": _one_line(overview),
        "objectives": objectives,
        "theory": _one_line(theory),
        "formula": profile.formula,
        "algorithm": profile.algorithm,
        "example": profile.example,
        "exampleSteps": profile.example_steps,
        "check": profile.check,
        "commonMistakes": profile.mistakes,
        "tasks": tasks,
        "summary": f"После урока ученик должен уверенно решать базовые задания по теме «{title}» без шаблонных ошибок.",
    }


def _detect_lesson_kind(title: str, order_index: int) -> Literal["theory", "practice"]:
    lowered = title.lower()
    if "теория" in lowered:
        return "theory"
    if "практик" in lowered:
        return "practice"
    return "theory" if order_index == 1 else "practice"


